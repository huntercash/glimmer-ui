// tokens.json is the one source of truth for both platforms.
// Run `node build-tokens.mjs` after editing it; it rewrites css/tokens.css and Sources/Glimmer/Tokens.swift.
import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("tokens.json", import.meta.url)));
const out = (path, text) => writeFileSync(new URL(path, import.meta.url), text);
const camel = (s) => s.replace(/-(.)/g, (_, c) => c.toUpperCase());
const banner = "Generated by build-tokens.mjs from tokens.json. Do not edit.";

const colors = Object.entries(t.color);
const radii = Object.entries(t.radius);
const durations = Object.entries(t.duration);
// The bundled faces first, then the platform's own, so text still renders if a font file fails to load.
const fontStacks = {
  font: `"${t.font.sans}", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
  mono: `"${t.font.mono}", ui-monospace, "SF Mono", Menlo, Consolas, monospace`,
};

for (const [name, hex] of colors)
  if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(hex))
    throw new Error(`tokens.json: color.${name} is "${hex}", expected #rrggbb or #rrggbbaa`);

// The light theme only changes these; everything else (accents, corners, fonts) is shared.
const light = Object.entries(t.light);
for (const [name, hex] of light)
  if (!(name in t.color) || !/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(hex))
    throw new Error(`tokens.json: light.${name} must override an existing colour with #rrggbb or #rrggbbaa`);
// --gl-tint is the colour of subtle overlays and hairlines (white on dark, black on light); --gl-shadow is drop-shadow strength.
// --gl-ink is how far accent-coloured text (links, badges, outline buttons) is darkened towards the text colour, so it stays readable on light.
const lightBlock = (indent) => [...light.map(([k, v]) => `--gl-${k}: ${v};`), "--gl-tint: 0 0 0;", "--gl-shadow: 0.18;", "--gl-ink: 45%;", "color-scheme: light;"].map((l) => indent + l).join("\n");

// @theme is a Tailwind v4 at-rule (gives you bg-primary, text-muted, ...). Browsers without Tailwind ignore it.
out("css/tokens.css", `/* ${banner} */
:root {
${[
  ...Object.entries(fontStacks).map(([k, v]) => `  --gl-${k}: ${v};`),
  ...colors.map(([k, v]) => `  --gl-${k}: ${v};`),
  "  --gl-tint: 255 255 255;",
  "  --gl-shadow: 0.75;",
  "  --gl-ink: 0%;",
  ...radii.map(([k, v]) => `  --gl-radius-${k}: ${v}px;`),
  ...durations.map(([k, v]) => `  --gl-duration-${k}: ${v}ms;`),
].join("\n")}
}
/* Light theme: data-theme="light" on <html> or any element. data-theme="auto" follows the system setting. */
[data-theme="light"] {
${lightBlock("  ")}
}
@media (prefers-color-scheme: light) {
  [data-theme="auto"] {
${lightBlock("    ")}
  }
}
/* Paper is light: print with the light theme whatever the screen shows. */
@media print {
  :root, [data-theme] {
${lightBlock("    ")}
  }
}
@theme inline {
  --font-sans: var(--gl-font);
  --font-mono: var(--gl-mono);
${colors.map(([k]) => `  --color-${k}: var(--gl-${k});`).join("\n")}
}
`);

// One explicit rule per colour, listing every component that takes a colour suffix (btn-primary, badge-success...).
// Explicit on purpose: an earlier substring selector also tinted unrelated classes such as Tailwind's text-primary.
const colourable = ["glass", "aura", "flare", "btn", "link", "checkbox", "radio", "toggle", "range", "rating", "card", "badge", "status",
  "stat", "timeline", "alert", "progress", "radial", "orb", "step", "search", "navbar", "dock", "modal", "drawer", "popover", "mockup-window"];
out("css/colors.css", `/* ${banner} Must load last. */
@layer components {
${["primary", "secondary", "success", "warning", "danger"].map((c) => `  ${colourable.map((b) => `.${b}-${c}`).join(", ")} { --c: var(--gl-${c}); }`).join("\n")}
}
`);

const channel = (hex, i) => (parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(3);
const swiftColor = (hex) =>
  `Color(.sRGB, red: ${channel(hex, 1)}, green: ${channel(hex, 3)}, blue: ${channel(hex, 5)}, opacity: ${hex.length === 9 ? channel(hex, 7) : 1})`;

out("Sources/Glimmer/Tokens.swift", `// ${banner}
import SwiftUI

public enum Tokens {
${[
  `    public static let fontSans = ${JSON.stringify(t.font.sans)}`,
  `    public static let fontMono = ${JSON.stringify(t.font.mono)}`,
  ...colors.map(([k, v]) => `    public static let ${camel(k)} = ${swiftColor(v)}`),
  ...radii.map(([k, v]) => `    public static let ${camel(`radius-${k}`)}: CGFloat = ${v}`),
  ...durations.map(([k, v]) => `    public static let ${camel(`duration-${k}`)}: Double = ${v / 1000}`),
].join("\n")}
}
`);
