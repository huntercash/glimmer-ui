// Generates the two alternative builds from the hand-written CSS. Run `npm run build` after changing any file in css/.
//   css/prefixed.css   every class renamed with a gl- prefix, for pages where names like .btn or .card are already taken
//   css/tailwind.css   the single-rule modifier classes again as Tailwind v4 utilities, so variants work: md:btn-lg, hover:btn-primary
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const read = (name) => readFileSync(new URL(`css/${name}`, import.meta.url), "utf8");
const parts = [...read("components.css").matchAll(/@import "\.\/(.+?)";/g)].map((m) => m[1]);
const bare = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");
// charts.js writes its own class names into the SVG, so chart classes keep their names in both builds.
const renamed = parts.filter((name) => !["tokens.css", "charts.css"].includes(name));

/** Adds the prefix to every class selector, leaving url(...) and quoted strings (which also contain dots) alone. */
export const prefix = (css, by = "gl-") =>
  bare(css).split(/(url\([^)]*\)|"[^"]*"|'[^']*')/).map((chunk, i) => (i % 2 ? chunk : chunk.replace(/\.([a-z][a-z0-9-]*)/g, `.${by}$1`))).join("");

/** Rules whose selector is just a class (or a list of them) and whose name has a hyphen: the modifiers, sizes and colours. */
export function utilities(css) {
  const found = new Map();
  // Rules inside @media and @supports only apply under that condition, so they are not part of a class's plain definition.
  const plain = bare(css).replace(/@(media|supports|keyframes)[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, "");
  for (const [, selector, body] of plain.matchAll(/([^{};]+)\{([^{}]*)\}/g)) {
    const parts = selector.split(",").map((s) => s.trim());
    if (!parts.every((s) => /^\.[a-z][a-z0-9-]*$/.test(s))) continue; // only rules made of plain single classes
    for (const name of parts.map((s) => s.slice(1)).filter((s) => s.includes("-")))
      found.set(name, [...(found.get(name) ?? []), body.trim().replace(/\s+/g, " ")]);
  }
  return [...found].map(([name, bodies]) => `@utility ${name} { ${bodies.join(" ")} }`).join("\n");
}

export function build() {
  const banner = "/* Generated by build-css.mjs from the files in css/. Do not edit. */\n";
  return {
    "css/prefixed.css": `${banner}/* Every class with a gl- prefix: .gl-btn, .gl-card, .gl-glass, .gl-frost-1. Use this file instead of the default entry.
   Chart classes keep their names, and so do attributes (data-tip, data-done, data-theme). It leaves the page itself alone:
   add css/page.css if you want Glimmer's background, text colour and focus ring as well. */\n` +
      parts.map((name) => (renamed.includes(name) ? prefix(read(name)) : read(name)).trim()).join("\n\n") + "\n",
    "css/tailwind.css": `${banner}/* Tailwind CSS v4 only. Import after Glimmer to use its modifier classes with variants: md:btn-lg, hover:btn-primary, lg:frost-3.
   @import "tailwindcss"; @import "@glimmer-ui-core/glimmer"; @import "@glimmer-ui-core/glimmer/css/tailwind.css";
   Covers classes defined by a single plain rule (sizes, colours, frost levels). Component classes themselves need no variant. */\n` +
      utilities(renamed.map(read).join("\n")) + "\n",
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) for (const [path, text] of Object.entries(build())) writeFileSync(new URL(path, import.meta.url), text);
